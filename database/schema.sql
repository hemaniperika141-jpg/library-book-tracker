create table if not exists users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  role text not null default 'librarian' check (role in ('librarian')),
  created_at timestamptz not null default now()
);

create table if not exists books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null,
  isbn text unique,
  category text,
  publication_year integer check (publication_year is null or publication_year between 0 and 2100),
  status text not null default 'available' check (status in ('available','borrowed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists transactions (
  id bigint generated by default as identity primary key,
  book_id bigint not null references books(id) on delete restrict,
  member_name text not null,
  member_email text not null,
  status text not null default 'borrowed' check (status in ('borrowed','returned')),
  borrowed_at timestamptz not null default now(),
  returned_at timestamptz
);

create index if not exists books_title_idx on books(title);
create index if not exists books_status_idx on books(status);
create index if not exists transactions_book_idx on transactions(book_id);
create index if not exists transactions_member_email_idx on transactions(member_email);

create or replace function set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists books_updated_at on books;
create trigger books_updated_at before update on books
for each row execute function set_updated_at();

